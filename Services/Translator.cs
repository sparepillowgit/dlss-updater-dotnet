        public event PropertyChangedEventHandler PropertyChanged;

        public event EventHandler LanguageChanged;

        public string Language
        {
            get { return _language; }
            set
            {
                if (string.IsNullOrEmpty(value) ||
                    !Tables.ContainsKey(value) ||
                    string.Equals(value, _language, StringComparison.OrdinalIgnoreCase))
                {
                    return;
                }

                _language = value;
                SaveLanguage(value);
                PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(Language)));
                PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(Binding.IndexerName));
                LanguageChanged?.Invoke(this, EventArgs.Empty);
            }
        }

        public string this[string key]
        {
            get { return Get(key); }
        }

        public static string T(string key)
        {
            return Instance.Get(key);
        }

        public static string T(string key, params object[] args)
        {
            return string.Format(CultureInfo.CurrentCulture, Instance.Get(key), args);
        }

        private string Get(string key)
        {
            Dictionary<string, string> table;
            string value;

            if (Tables.TryGetValue(_language, out table) &&
                table.TryGetValue(key, out value))
            {
                return value;
            }

            if (Tables[DefaultLanguage].TryGetValue(key, out value))
            {
                return value;
            }

            return key;
        }

        private static string DetectSystemLanguage()
        {
            string systemLanguage = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName;
            return Tables.ContainsKey(systemLanguage) ? systemLanguage : DefaultLanguage;
        }

        private static string GetSettingsPath()
        {
            return Path.Combine(
                Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData),
                "DLSS Updater",
                "language.txt");
        }

        private static string LoadSavedLanguage()
        {
            try
            {
                string path = GetSettingsPath();
                if (!File.Exists(path))
                {
                    return null;
                }

                string language = File.ReadAllText(path).Trim();
                return Tables.ContainsKey(language) ? language : null;
            }
            catch
            {
                return null;
            }
        }

        private static void SaveLanguage(string language)
        {
            try
            {
                string path = GetSettingsPath();
                Directory.CreateDirectory(Path.GetDirectoryName(path));
                File.WriteAllText(path, language);
            }
            catch
            {
            }
        }
    }

    public sealed class TrExtension : MarkupExtension
    {
        public TrExtension()
        {
        }

        public TrExtension(string key)
        {
            Key = key;
        }

        public string Key { get; set; }

        public override object ProvideValue(IServiceProvider serviceProvider)
        {
            Binding binding = new Binding("[" + Key + "]")
            {
                Source = Translator.Instance,
                Mode = BindingMode.OneWay
            };

            return binding.ProvideValue(serviceProvider);
        }
